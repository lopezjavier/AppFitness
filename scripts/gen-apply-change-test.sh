#!/usr/bin/env bash
# Regenerates supabase/tests/coach_apply_change.test.sql: the pgTAP test of coach_apply_change with the shared fixture
# (supabase/functions/coach/fixtures/folder_changes.json) embedded verbatim. folderChanges.test.ts fails when the two
# drift apart, so run this script after editing the fixture.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
fixture="$root/supabase/functions/coach/fixtures/folder_changes.json"
out="$root/supabase/tests/coach_apply_change.test.sql"
{
  cat <<'HEADER'
-- pgTAP: coach_apply_change against the fixture shared with folderChanges.test.ts (T-207).
-- GENERATED by scripts/gen-apply-change-test.sh: edit supabase/functions/coach/fixtures/folder_changes.json and re-run.
begin;
create extension if not exists pgtap with schema extensions;
set local search_path = extensions, public;

select plan(12);

create function pg_temp.fixture() returns jsonb language sql as $fixture$ select $j$
HEADER
  cat "$fixture"
  cat <<'FOOTER'
$j$::jsonb $fixture$;

-- The comparable view of a routine: what is saved, without the ids (which differ between TypeScript and the database).
create function pg_temp.proj(p_routine jsonb) returns jsonb language sql as $$
  select coalesce(jsonb_agg(jsonb_build_object(
    'exercise_key', x.e -> 'exercise_key', 'superset_group', x.e -> 'superset_group',
    'rest_seconds', x.e -> 'rest_seconds', 'rep_min', x.e -> 'rep_min', 'rep_max', x.e -> 'rep_max',
    'target_rpe', x.e -> 'target_rpe', 'notes', x.e -> 'notes',
    'sets', (select jsonb_agg(jsonb_build_array(t.s -> 'reps', t.s -> 'set_type', t.s -> 'weight_kg') order by t.o)
             from jsonb_array_elements(x.e -> 'sets') with ordinality t(s, o))) order by x.n), '[]'::jsonb)
  from jsonb_array_elements(p_routine -> 'exercises') with ordinality x(e, n) $$;

select is(pg_temp.proj(public.coach_apply_change(pg_temp.fixture() -> 'routine', c.value -> 'change')),
          coalesce(c.value -> 'after', pg_temp.fixture() -> 'base'), c.value ->> 'name')
from jsonb_array_elements(pg_temp.fixture() -> 'cases') c;

select * from finish();
rollback;
FOOTER
} > "$out"

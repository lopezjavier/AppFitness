#!/usr/bin/env python3
"""Generate the T-179 long-band catalogue and exercise-alternatives migrations (ADR-83).

Usage:
  python scripts/generate-band-long.py --band-long <band-long-exercises.csv> \
      --alternatives <exercise-with-alternatives.csv> [--bundle <exercises bundle dir>]

Writes supabase/migrations/20261213100100_band_long_catalog.sql and
supabase/migrations/20261213100300_exercise_alternatives_seed.sql (keys and scores only, no text).
With --bundle (the gitignored composeResources/files/exercises directory) it also appends the 30 library.json
entries and copies the media of each media_source_key to the new band-long-* key; nothing else is written there.
Fails on a missing source key, a score mismatch, a missing reverse entry or a pair count other than 402.
"""
import argparse
import csv
import glob
import json
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CATALOG_MIGRATION = os.path.join(ROOT, "supabase", "migrations", "20261213100100_band_long_catalog.sql")
SEED_MIGRATION = os.path.join(ROOT, "supabase", "migrations", "20261213100300_exercise_alternatives_seed.sql")
EXPECTED_NEW = 30
EXPECTED_PAIRS = 402
KEY_RE = re.compile(r"^[a-z0-9][a-z0-9-]*$")


class GeneratorError(Exception):
    pass


def read_csv(path):
    with open(path, encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def parse_alternatives_cell(cell):
    """'a=0.9;b=1' -> [('a', '0.90'), ('b', '1.00')]"""
    out = []
    for entry in (cell or "").split(";"):
        entry = entry.strip()
        if not entry:
            continue
        key, sep, score = entry.partition("=")
        if not sep or not KEY_RE.match(key.strip()):
            raise GeneratorError(f"bad alternative entry: {entry!r}")
        try:
            value = float(score)
        except ValueError:
            raise GeneratorError(f"bad score in {entry!r}")
        if not 0 < value <= 1:
            raise GeneratorError(f"score out of range in {entry!r}")
        out.append((key.strip(), f"{value:.2f}"))
    return out


def build_pairs(rows, expected=EXPECTED_PAIRS, known_keys=None):
    """rows: [(key, [(other, score)])] -> {(a, b): score} with a < b. Asserts symmetry and equal scores."""
    directed = {}
    for key, alts in rows:
        if known_keys is not None and key not in known_keys:
            raise GeneratorError(f"unknown exercise key {key}")
        for other, score in alts:
            if other == key:
                raise GeneratorError(f"self alternative {key}")
            if known_keys is not None and other not in known_keys:
                raise GeneratorError(f"unknown alternative key {other} (in {key})")
            if (key, other) in directed:
                raise GeneratorError(f"duplicate entry {key} -> {other}")
            directed[(key, other)] = score
    pairs = {}
    for (a, b), score in directed.items():
        back = directed.get((b, a))
        if back is None:
            raise GeneratorError(f"missing reverse entry for {a} -> {b}")
        if back != score:
            raise GeneratorError(f"score mismatch {a}<->{b}: {score} vs {back}")
        pairs[(min(a, b), max(a, b))] = score
    if len(pairs) != expected:
        raise GeneratorError(f"expected {expected} pairs, got {len(pairs)}")
    return dict(sorted(pairs.items()))


def check_sources(band_rows, catalog_keys):
    for r in band_rows:
        if r["media_source_key"] not in catalog_keys:
            raise GeneratorError(f"source key {r['media_source_key']} is not in the catalogue")


def catalog_keys_from_migrations():
    keys = set()
    for path in sorted(glob.glob(os.path.join(ROOT, "supabase", "migrations", "*.sql"))):
        if os.path.abspath(path) in (os.path.abspath(CATALOG_MIGRATION), os.path.abspath(SEED_MIGRATION)):
            continue
        with open(path, encoding="utf-8") as f:
            keys.update(re.findall(r"\('([a-z0-9][a-z0-9-]*)',\s*'[a-z_]+',\s*'[a-z_]+',", f.read()))
    return keys


def render_catalog(band_rows):
    values = ",\n".join(f"  ('{r['key']}', '{r['media_source_key']}')" for r in band_rows)
    return f"""-- T-179 (ADR-83): 30 long-band catalogue exercises, one per cable exercise.
-- Generated by scripts/generate-band-long.py. Keys and our own enum values only: names, descriptions and
-- images live in the client bundle (ADR-38, ADR-39). Idempotent (on conflict do nothing).
-- muscle_group, metric_type and movement_pattern are copied from the cable source row.

insert into public.exercises (key, muscle_group, equipment, metric_type, movement_pattern, per_hand, is_custom, name)
select m.new_key, s.muscle_group, 'band_long', s.metric_type, s.movement_pattern, false, false, null
from (values
{values}
) as m(new_key, source_key)
join public.exercises s on s.key = m.source_key and not s.is_custom
on conflict (key) where key is not null do nothing;

do $$
begin
  if (select count(*) from public.exercises where key like 'band-long-%' and equipment = 'band_long') <> {len(band_rows)} then
    raise exception 'band-long catalogue incomplete: a cable source row is missing';
  end if;
end $$;
"""


def render_seed(pairs):
    values = ",\n".join(f"  ('{a}', '{b}', {s})" for (a, b), s in pairs.items())
    return f"""-- T-179 (ADR-83): curated exercise alternatives, {len(pairs)} unordered pairs.
-- Generated by scripts/generate-band-long.py from the maintainer's list: one row per pair, scores symmetric by
-- construction. Idempotent (on conflict do nothing).

insert into public.exercise_alternatives (exercise_id, alternative_id, similarity)
select least(a.id, b.id), greatest(a.id, b.id), v.similarity
from (values
{values}
) as v(key_a, key_b, similarity)
join public.exercises a on a.key = v.key_a and not a.is_custom
join public.exercises b on b.key = v.key_b and not b.is_custom
on conflict do nothing;

do $$
begin
  if (select count(*) from public.exercise_alternatives) < {len(pairs)} then
    raise exception 'exercise_alternatives seed incomplete: a key is missing from the catalogue';
  end if;
end $$;
"""


def write_text(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def update_bundle(bundle_dir, band_rows):
    lib_path = os.path.join(bundle_dir, "library.json")
    with open(lib_path, encoding="utf-8") as f:
        payload = json.load(f)
    exercises = payload["exercises"]
    copied = 0
    for r in band_rows:
        src = exercises.get(r["media_source_key"])
        if src is None:
            raise GeneratorError(f"{r['media_source_key']} is not in library.json")
        poses = src.get("poses", ["start"])
        exercises[r["key"]] = {
            "name": r["name"],
            "description": r["description"],
            "instructions": [s.strip() for s in r["instructions"].split("|") if s.strip()],
            "tips": [s.strip() for s in r["tips"].split("|") if s.strip()],
            "poses": poses,
        }
        for pose in poses:
            s = os.path.join(bundle_dir, "images", f"{r['media_source_key']}-{pose}.webp")
            if not os.path.isfile(s):
                raise GeneratorError(f"missing image {s}")
            shutil.copyfile(s, os.path.join(bundle_dir, "images", f"{r['key']}-{pose}.webp"))
            copied += 1
    with open(lib_path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(payload, f, ensure_ascii=False, separators=(",", ":"))
        f.write("\n")
    return copied


def main(argv=None):
    p = argparse.ArgumentParser()
    p.add_argument("--band-long", required=True)
    p.add_argument("--alternatives", required=True)
    p.add_argument("--bundle")
    args = p.parse_args(argv)
    try:
        band_rows = read_csv(args.band_long)
        if len(band_rows) != EXPECTED_NEW:
            raise GeneratorError(f"expected {EXPECTED_NEW} band-long rows, got {len(band_rows)}")
        for r in band_rows:
            if r["key"] != "band-long-" + r["media_source_key"] or not KEY_RE.match(r["key"]):
                raise GeneratorError(f"unexpected key {r['key']}")
            if r["equipment"] != "band_long":
                raise GeneratorError(f"{r['key']}: equipment must be band_long")
        cat_keys = catalog_keys_from_migrations()
        check_sources(band_rows, cat_keys)
        alt_rows = [(r["key"], parse_alternatives_cell(r["alternative_exercises"])) for r in read_csv(args.alternatives)]
        known = cat_keys | {r["key"] for r in band_rows}
        pairs = build_pairs(alt_rows, known_keys=known)
        for r in band_rows:
            if pairs.get((min(r["media_source_key"], r["key"]), max(r["media_source_key"], r["key"]))) != "1.00":
                raise GeneratorError(f"{r['key']} is not paired with its cable source at 1.00")
        write_text(CATALOG_MIGRATION, render_catalog(band_rows))
        write_text(SEED_MIGRATION, render_seed(pairs))
        print(f"Wrote {len(band_rows)} exercises and {len(pairs)} pairs")
        if args.bundle:
            print(f"Library/media: copied {update_bundle(args.bundle, band_rows)} images")
    except GeneratorError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
